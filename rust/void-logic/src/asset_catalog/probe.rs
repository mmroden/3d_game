//! The asset probe: the final accounting step of `make assets`. It writes
//! `catalog/models.generated.toml` — every installed enemy model, keyed by
//! file stem, valued by its `res://` path. `[[enemy]] model = "<key>"`
//! resolves against this catalog, so a typo or a missing install is a link
//! error naming the culprit — never an invisible drone at runtime. Every
//! catalogued file's geometry is parsed, so a broken export from ANY
//! pipeline step fails the probe, not a run.
//!
//! The output is GENERATED-BUT-COMMITTED (like `VOCABULARY.md`): the game
//! embeds it at compile time, machinery rewrites it, hands never do.
//! Emission goes through the same serde schema the loader reads
//! ([`schema::ModelsFile`]), so the round-trip cannot drift.
//!
//! It also writes `catalog/kits.generated.toml` — each kit's tile/story
//! DERIVED from its assembly recipe (owner 2026-07-05: no authored
//! dimensions anywhere; two hand-transcribed copies had already drifted
//! into folklore). Kit pieces bake their stack position into mesh space,
//! so for a layered kit the story is the TOP layer's y-max (a Top piece
//! spans y 3..5) and the tile is the straight wall's z-range; for a panel
//! kit the pool's uniform square extent is the pitch. The recipes are the
//! wall/panel sets in [`crate::asset_catalog`]; every set of a kit must
//! derive the same grid or the probe fails.
//!
//! Test-gated: the `gltf` parser is a dev-dependency; the probe runs as an
//! `--ignored` writer test (the `regenerate_*` house pattern) from
//! `make assets`.

