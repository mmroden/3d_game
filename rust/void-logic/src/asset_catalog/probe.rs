/// (positive-side, negative-side) relief mass along `thin`: geometry
/// weighed by its distance BEYOND the base slab — the peak flat-area
/// depth bin. The heavier side is the greeble. Convention-free where
/// the winding sum it replaced read modeling conventions (the bake
/// 5/6/8 oscillation saga); scripts/split-panels.py computes the SAME
/// split, so Transform and probe cannot disagree by construction.
fn relief_split(tris: &[[[f32; 3]; 3]], thin: usize) -> (f32, f32) {
    const BINS: usize = 32;
    let mut lo = f32::INFINITY;
    let mut hi = f32::NEG_INFINITY;
    for t in tris {
        for v in t {
            lo = lo.min(v[thin]);
            hi = hi.max(v[thin]);
        }
    }
    let depth = hi - lo;
    if !depth.is_finite() || depth <= f32::EPSILON {
        return (0.0, 0.0);
    }
    let mut flat = [0.0f32; BINS];
    let mut weighed: Vec<(f32, f32)> = Vec::with_capacity(tris.len());
    for t in tris {
        let e1 = [t[1][0] - t[0][0], t[1][1] - t[0][1], t[1][2] - t[0][2]];
        let e2 = [t[2][0] - t[0][0], t[2][1] - t[0][1], t[2][2] - t[0][2]];
        let cross = [
            e1[1] * e2[2] - e1[2] * e2[1],
            e1[2] * e2[0] - e1[0] * e2[2],
            e1[0] * e2[1] - e1[1] * e2[0],
        ];
        let norm = (cross[0] * cross[0] + cross[1] * cross[1] + cross[2] * cross[2]).sqrt();
        let area = norm / 2.0;
        if area <= 0.0 {
            continue;
        }
        let c = (t[0][thin] + t[1][thin] + t[2][thin]) / 3.0;
        // Only face-on area votes for the base slab: a greeble's side
        // walls are relief, not a candidate base plane.
        let bin = (((c - lo) / depth) * BINS as f32) as usize;
        flat[bin.min(BINS - 1)] += area * (cross[thin].abs() / norm);
        weighed.push((area, c));
    }
    let peak = (0..BINS).max_by(|&a, &b| flat[a].total_cmp(&flat[b])).unwrap();
    let bin_lo = lo + depth * peak as f32 / BINS as f32;
    let bin_hi = lo + depth * (peak + 1) as f32 / BINS as f32;
    let mut pos = 0.0;
    let mut neg = 0.0;
    for (area, c) in weighed {
        pos += area * (c - bin_hi).max(0.0);
        neg += area * (bin_lo - c).max(0.0);
    }
    (pos, neg)
}

/// Mean of channel `offset` across pixels of `stride` bytes, as 0..1;
/// 1.0 (the glTF neutral multiplier) when the channel does not exist.
fn channel_mean(pixels: &[u8], stride: usize, offset: usize) -> f32 {
    if offset >= stride || pixels.len() < stride {
        return 1.0;
    }
    let mut sum = 0u64;
    let mut n = 0u64;
    for px in pixels.chunks_exact(stride) {
        sum += px[offset] as u64;
        n += 1;
    }
    if n == 0 {
        return 1.0;
    }
    sum as f32 / (n as f32 * 255.0)
}

/// Whether a baked file's census record inverts for the kit's authored
/// per-piece flips: every source overridden, or none — a mixed stack
/// has no single artist front to record.
fn override_inversion(sources: &[String], flips: &[String]) -> Result<bool, String> {
    let overridden = sources.iter().filter(|s| flips.contains(s)).count();
    match overridden {
        0 => Ok(false),
        n if n == sources.len() => Ok(true),
        _ => Err(format!(
            "sources {sources:?} mix authored detail_flip pieces with plain ones — \
             no single artist front; author both or neither"
        )),
    }
}

fn variant_census(
    path: &Path,
    declared: &super::schema::ManifestVariantRaw,
    flips: &[String],
) -> super::schema::GeneratedVariantRaw {
    let m = measure(path);
    // The census's `detail` MEANS the artist's front: the measured
    // relief side, inverted for pieces the kit AUTHORS as detailed on
    // their relief-light side.
    let inverted = override_inversion(&declared.sources, flips)
        .unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    super::schema::GeneratedVariantRaw {
        sources: declared.sources.clone(),
        role: declared.role,
        face: m.face,
        thick: m.thick,
        axis: m.axis,
        detail: if inverted { m.detail.opposite() } else { m.detail },
        relief: m.relief,
        coverage: m.coverage,
        stretch: declared.stretch,
        tris: m.tris,
        textures: m.textures,
    }
}

fn measure(path: &Path) -> Measured {
    let (doc, buffers, images) = gltf::import(path)
        .unwrap_or_else(|e| panic!("{}: not an importable glTF ({e})", path.display()));

    let mut tris: Vec<[[f32; 3]; 3]> = Vec::new();
    fn visit(
        node: gltf::Node,
        parent: [[f32; 4]; 4],
        buffers: &[gltf::buffer::Data],
        tris: &mut Vec<[[f32; 3]; 3]>,
    ) {
        let world = mul(parent, node.transform().matrix());
        if let Some(mesh) = node.mesh() {
            for prim in mesh.primitives() {
                let reader = prim.reader(|b| Some(&buffers[b.index()]));
                let Some(pos) = reader.read_positions() else { continue };
                let verts: Vec<[f32; 3]> = pos
                    .map(|p| {
                        let mut out = [0.0; 3];
                        for (i, o) in out.iter_mut().enumerate() {
                            *o = world[0][i] * p[0]
                                + world[1][i] * p[1]
                                + world[2][i] * p[2]
                                + world[3][i];
                        }
                        out
                    })
                    .collect();
                let idx: Vec<u32> = match reader.read_indices() {
                    Some(ix) => ix.into_u32().collect(),
                    None => (0..verts.len() as u32).collect(),
                };
                for tri in idx.chunks_exact(3) {
                    tris.push([
                        verts[tri[0] as usize],
                        verts[tri[1] as usize],
                        verts[tri[2] as usize],
                    ]);
                }
            }
        }
        for child in node.children() {
            visit(child, world, buffers, tris);
        }
    }
    for scene in doc.scenes() {
        for node in scene.nodes() {
            visit(node, IDENTITY, &buffers, &mut tris);
        }
    }
    assert!(!tris.is_empty(), "{}: no triangles", path.display());

    let mut lo = [f32::INFINITY; 3];
    let mut hi = [f32::NEG_INFINITY; 3];
    for t in &tris {
        for v in t {
            for i in 0..3 {
                lo[i] = lo[i].min(v[i]);
                hi[i] = hi[i].max(v[i]);
            }
        }
    }
    let ext = [hi[0] - lo[0], hi[1] - lo[1], hi[2] - lo[2]];
    // The plate's thin axis; the other two are the face, larger first.
    let thin = (0..3).min_by(|&a, &b| ext[a].total_cmp(&ext[b])).unwrap();
    let (u, v) = match thin {
        0 => (1, 2),
        1 => (0, 2),
        _ => (0, 1),
    };
    let (u, v) = if ext[u] >= ext[v] { (u, v) } else { (v, u) };

    // The detail direction: the relief-heavy side along the thin axis —
    // where the artist's greeble is. Ties (a symmetric or featureless
    // plate) break positive, deterministically, on both sides of the
    // pipeline.
    let (relief_pos, relief_neg) = relief_split(&tris, thin);
    use crate::room_template::ConnectorFacing;
    let positive = relief_pos >= relief_neg;
    let detail = match (thin, positive) {
        (0, true) => ConnectorFacing::PosX,
        (0, false) => ConnectorFacing::NegX,
        (1, true) => ConnectorFacing::PosY,
        (1, false) => ConnectorFacing::NegY,
        (2, true) => ConnectorFacing::PosZ,
        _ => ConnectorFacing::NegZ,
    };

    // Material facts, straight from the file. Effective shading is
    // FACTOR × MAP CHANNEL (glTF: roughness rides green, metallic rides
    // blue), so the census records both — factors alone lie in both
    // directions (a matte factor under an absent map, a neutral 1.0
    // factor over a white metal channel).
    let mut metallic = 0.0f32;
    let mut roughness = 1.0f32;
    let mut mr_map = false;
    let mut any_material = false;
    let mut metallic_px = 1.0f32;
    let mut rough_px = 1.0f32;
    let mut maps = 0u32;
    for mat in doc.materials() {
        let pbr = mat.pbr_metallic_roughness();
        any_material = true;
        metallic = metallic.max(pbr.metallic_factor());
        roughness = roughness.min(pbr.roughness_factor());
        if let Some(tex) = pbr.metallic_roughness_texture() {
            mr_map = true;
            let img = &images[tex.texture().source().index()];
            let stride = img.pixels.len() / (img.width as usize * img.height as usize).max(1);
            let (g, b) = (
                channel_mean(&img.pixels, stride, 1),
                channel_mean(&img.pixels, stride, 2),
            );
            // Across materials keep the SHINIEST verdict — one chrome
            // material on a matte piece still glares.
            if maps == 0 || b > metallic_px {
                metallic_px = b;
            }
            if maps == 0 || g < rough_px {
                rough_px = g;
            }
            maps += 1;
        }
    }
    if !any_material {
        metallic = 1.0;
    }

    let flat: Vec<[[f32; 2]; 3]> = tris
        .iter()
        .map(|t| t.map(|p| [p[u], p[v]]))
        .collect();
    let relief_total = relief_pos + relief_neg;
    Measured {
        face: [ext[u], ext[v]],
        thick: ext[thin],
        axis: match thin {
            0 => super::schema::ThinAxis::X,
            1 => super::schema::ThinAxis::Y,
            _ => super::schema::ThinAxis::Z,
        },
        detail,
        relief: if relief_total > 0.0 {
            (relief_pos - relief_neg).abs() / relief_total
        } else {
            0.0
        },
        coverage: face_coverage(&flat, [lo[u], lo[v]], [hi[u], hi[v]]),
        tris: tris.len() as u32,
        textures: doc.images().len().min(u8::MAX as usize) as u8,
        metallic,
        roughness,
        mr_map,
        metallic_px,
        rough_px,
    }
}

/// Derive one kit's grid from its installed meshes. Layered: tile = the
/// straight wall's z-range, story = the top layer's mesh-space y-max
/// (pieces bake their stack position, so the ceiling piece's top IS the
/// story) — every recipe set covering the kit must agree. Panel: the kit
/// is CENSUSED piece by piece (face, thickness, thin axis, coverage,
/// tris, textures)
/// and the grid is the largest square plate face — square plates define
/// the cell; conversion snaps provider slop onto them (split-panels.py).
fn derive_kit_grid(
    repo: &Path,
    key: &str,
    kit: &super::schema::KitRaw,
) -> GeneratedKitRaw {
    use super::schema::KitParadigm;

    if kit.paradigm == KitParadigm::Panel {
        // The Transform's manifest names its baked variants; every other
        // installed glb is a source PIECE. No manifest = no bake yet.
        let manifest: Option<super::schema::TransformManifest> =
            std::fs::read_to_string(repo.join(&kit.install_dir).join("manifest.toml"))
                .ok()
                .map(|s| {
                    toml::from_str(&s).unwrap_or_else(|e| {
                        panic!("kit '{key}': manifest.toml does not parse: {e}")
                    })
                });
        let declared = manifest.map(|m| m.variants).unwrap_or_default();

        let files = gltf_files(&repo.join(&kit.install_dir));
        let mut pieces: BTreeMap<String, super::schema::GeneratedPieceRaw> = BTreeMap::new();
        let mut variants: BTreeMap<String, super::schema::GeneratedVariantRaw> = BTreeMap::new();
        for f in &files {
            let stem = f.file_stem().unwrap().to_string_lossy().into_owned();
            match declared.get(&stem) {
                Some(d) => {
                    variants.insert(stem, variant_census(f, d, &kit.detail_flip));
                }
                None => {
                    pieces.insert(stem, piece_census(f));
                }
            }
        }
        for stem in declared.keys() {
            assert!(
                variants.contains_key(stem),
                "kit '{key}': manifest declares '{stem}' but no such glb is installed"
            );
        }
        let square = |p: &&super::schema::GeneratedPieceRaw| -> bool {
            (p.face[0] - p.face[1]) <= 0.01 * p.face[0]
        };
        let pitch = pieces
            .values()
            .filter(square)
            .map(|p| p.face[0])
            .fold(0.0_f32, f32::max);
        assert!(
            pitch > 0.0,
            "kit '{key}': no square plate to derive a grid from — \
             a panel kit needs at least one"
        );
        let snapped = (pitch * 100.0).round() / 100.0;
        return GeneratedKitRaw {
            tile: snapped,
            story: snapped,
            pieces,
            variants,
        };
    }

    let install_dir = &kit.install_dir;
    let res_prefix = format!(
        "res://{}/",
        install_dir.trim_start_matches("godot/").trim_end_matches('/')
    );
    let mut grids: Vec<(String, f32, f32)> = Vec::new();

    for ws in ALL_WALL_SETS {
        if !ws.straight.wall.starts_with(&res_prefix) {
            continue;
        }
        let (wlo, whi) = aabb_bounds(&res_to_disk(repo, ws.straight.wall));
        let (_, chi) = aabb_bounds(&res_to_disk(repo, ws.straight.ceiling));
        grids.push((format!("wall set '{}'", ws.id), whi[2] - wlo[2], chi[1]));
    }

    let (first_src, mut tile, mut story) = grids
        .first()
        .unwrap_or_else(|| {
            panic!("kit '{key}': no recipe (wall set) covers {install_dir}")
        })
        .clone();
    // The grid step is what pieces SNAP to: sets may carry small decorative
    // overhangs (the window set's top lips 2 cm past the others), so agree
    // within 5 cm and take the minimum — a lip overlaps the next course
    // harmlessly, a gap would not.
    for (src, t, s) in &grids {
        assert!(
            (t - tile).abs() < super::schema::GRID_SNAP
                && (s - story).abs() < super::schema::GRID_SNAP,
            "kit '{key}': {src} derives {t:.2}/{s:.2} but {first_src} derives \
             {tile:.2}/{story:.2} — the kit's sets disagree on the grid"
        );
        tile = tile.min(*t);
        story = story.min(*s);
    }
    // Snap to the centimeter: meshes run a hair under their grid (the split
    // panels decimate to 2.997), and the grid is the SNAP step, not the
    // mesh — sub-cm slack is seam tolerance the assembler already absorbs.
    GeneratedKitRaw {
        tile: (tile * 100.0).round() / 100.0,
        story: (story * 100.0).round() / 100.0,
        pieces: Default::default(),
        variants: Default::default(),
    }
}

/// Each kit's grid, derived from recipe + installed meshes.
pub fn kit_grids() -> String {
    let repo = repo_root();
    let kits_file: KitsFile =
        toml::from_str(super::KITS_TOML).expect("kits.toml parses (the loader pins this)");
    let kits: BTreeMap<String, GeneratedKitRaw> = kits_file
        .kits
        .iter()
        // Fixed kits have no recipe to derive a grid from — their pitch is
        // the declared scale (the one authored-grid exception, see kits.toml).
        .filter(|(_, kit)| kit.paradigm != super::schema::KitParadigm::Fixed)
        .map(|(key, kit)| (key.clone(), derive_kit_grid(&repo, key, kit)))
        .collect();
    let body = toml::to_string(&GeneratedKitsFile { kits }).expect("serialize kit grids");
    format!(
        "{GENERATED_HEADER}\
         # Each kit's grid, DERIVED from its assembly recipe: layered kits\n\
         # from the straight wall's width and the top layer's mesh-space\n\
         # y-max (pieces bake their stack position); panel kits from the\n\
         # pool's uniform square extent. No dimension is ever authored.\n\
         \n{body}"
    )
}

